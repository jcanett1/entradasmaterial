-- ============================================================
CREATE TABLE IF NOT EXISTS public.kitteo_locations (
  id            serial        NOT NULL,
  rack          varchar(20)   NOT NULL,
  location_code varchar(20)   NOT NULL UNIQUE,
  status        varchar(20)   NOT NULL DEFAULT 'disponible',
  part_number   varchar(100)  NULL,
  qty           integer       NULL,
  boxes         integer       NULL,
  po            varchar(100)  NULL,
  entry_id      integer       NULL,
  description   text          NULL,
  registered_by varchar(100)  NULL,
  assigned_at   timestamp     NULL,
  CONSTRAINT kitteo_locations_pkey PRIMARY KEY (id)
) TABLESPACE pg_default;

CREATE INDEX IF NOT EXISTS idx_kitteo_locations_rack ON public.kitteo_locations(rack);
CREATE INDEX IF NOT EXISTS idx_kitteo_locations_status ON public.kitteo_locations(status);

